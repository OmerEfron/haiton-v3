import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { DATA } from '../../frontend/src/mocks/seed/haiton-data.js'
import { placeholderImage } from '../../frontend/src/mocks/seed/seed.ts'

const HOURS: Record<string, number> = {
  עכשיו: 0.05,
  'לפני שעה': 1,
  'לפני שעתיים': 2,
  'לפני 3 שעות': 3,
  'לפני 5 שעות': 5,
  אתמול: 24,
  'לפני יומיים': 48,
  'לפני 3 ימים': 72,
  'לפני 4 ימים': 96,
  'לפני 5 ימים': 120,
  'לפני שבוע': 168,
}

const EMAILS: Record<string, string> = {
  maya: 'maya.cohen@gmail.com',
  tamar: 'tamar.golan@gmail.com',
  omri: 'omri.dahan@gmail.com',
  mom: 'ilana.levi@gmail.com',
  shlomo: 'shlomo.ohayon@gmail.com',
}

type User = { id: string; name: string; email: string; onboarding: boolean; gender: string; birthYear: number }

const GENDERS = ['female', 'male', 'other'] as const

function profile(id: string) {
  let n = 0
  for (const c of id) n = (n * 33 + c.charCodeAt(0)) >>> 0
  return { gender: GENDERS[n % 3], birthYear: 1960 + (n % 45) }
}

type Article = {
  id: string
  authorId: string
  author: string
  time: string
  img?: string
  noPhoto?: boolean
  headline: string
  sub: string
  flash: string
  body: string[]
  prev?: string
}

const personas = Object.keys(DATA) as (keyof typeof DATA)[]
const personaIds = new Set(personas.map((k) => DATA[k].meId))
const users = new Map<string, User>()

function addUser(id: string, name: string, email?: string, onboarding = false) {
  const cur = users.get(id)
  if (!cur) {
    users.set(id, { id, name, email: email ?? `${id}@seed.haiton.local`, onboarding, ...profile(id) })
    return
  }
  if (email) cur.email = email
}

for (const key of personas) {
  const P = DATA[key]
  addUser(P.meId, P.meName, EMAILS[key], !!P.onboard)
}
for (const key of personas) {
  for (const p of DATA[key].people) addUser(p.id, p.name)
}
for (const key of personas) {
  for (const a of DATA[key].feed as Article[]) {
    if (personaIds.has(a.authorId)) continue
    const cur = users.get(a.authorId)
    if (!cur) addUser(a.authorId, a.author)
    else cur.name = a.author
  }
}

const links = new Set<string>()
function connect(a: string, b: string) {
  if (a === b) return
  links.add(`${a}\t${b}`)
  links.add(`${b}\t${a}`)
}

const articles = new Map<string, Article>()
const audience = new Map<string, Set<string>>()

for (const key of personas) {
  const P = DATA[key]
  for (const p of P.people) connect(P.meId, p.id)
  for (const a of P.feed as Article[]) {
    connect(P.meId, a.authorId)
    articles.set(a.id, a)
    const set = audience.get(a.id) ?? new Set()
    if (a.authorId !== P.meId) set.add(P.meId)
    audience.set(a.id, set)
  }
}

function q(s: string) {
  return `'${s.replaceAll("'", "''")}'`
}

function qArr(xs: string[]) {
  return `array[${xs.map(q).join(', ')}]::text[]`
}

const lines: string[] = [
  '-- generated by backend/scripts/gen-seed.ts — do not edit by hand',
  'truncate notifications, invites, facts, reports, hidden, reactions, article_audience, articles, group_members, groups, connections, users cascade;',
  '',
  'insert into users (id, email, name, onboarding, gender, birth_year) values',
  [...users.values()]
    .map((u) => `  (${q(u.id)}, ${q(u.email)}, ${q(u.name)}, ${u.onboarding}, ${q(u.gender)}, ${u.birthYear})`)
    .join(',\n') + ';',
  '',
]

if (links.size) {
  lines.push(
    'insert into connections (user_id, other_id) values',
    [...links].map((p) => {
      const [a, b] = p.split('\t')
      return `  (${q(a)}, ${q(b)})`
    }).join(',\n') + ';',
    '',
  )
}

const ordered: Article[] = []
const seen = new Set<string>()
function take(a: Article) {
  if (seen.has(a.id)) return
  if (a.prev && articles.has(a.prev)) take(articles.get(a.prev)!)
  seen.add(a.id)
  ordered.push(a)
}
for (const a of articles.values()) take(a)

lines.push('insert into articles (id, author_id, created_at, image_url, headline, sub, flash, body, prev_id) values')
lines.push(
  ordered
    .map((a) => {
      const hours = HOURS[a.time] ?? 0
      const img = a.noPhoto || !a.img ? 'null' : q(placeholderImage(a.img))
      const prev = a.prev ? q(a.prev) : 'null'
      return `  (${q(a.id)}, ${q(a.authorId)}, now() - interval '${hours} hours', ${img}, ${q(a.headline)}, ${q(a.sub)}, ${q(a.flash)}, ${qArr(a.body)}, ${prev})`
    })
    .join(',\n') + ';',
  '',
)

const audRows: string[] = []
for (const [id, set] of audience) {
  for (const uid of set) audRows.push(`  (${q(id)}, ${q(uid)})`)
}
if (audRows.length) {
  lines.push('insert into article_audience (article_id, user_id) values', audRows.join(',\n') + ';', '')
}

const factRows: string[] = []
for (const key of personas) {
  const P = DATA[key]
  P.facts.forEach((f, i) => {
    factRows.push(`  (${q(`${P.meId}_f${i + 1}`)}, ${q(P.meId)}, ${q(f.k)}, ${q(f.v)}, ${q(f.src)}, false)`)
  })
}
if (factRows.length) {
  lines.push('insert into facts (id, user_id, k, v, src, is_new) values', factRows.join(',\n') + ';', '')
}

const groupRows: string[] = []
const memberRows: string[] = []
for (const key of personas) {
  const P = DATA[key]
  P.groups.forEach((g, i) => {
    const id = `${P.meId}_g${i + 1}`
    groupRows.push(`  (${q(id)}, ${q(P.meId)}, ${q(g.name)})`)
    for (const m of g.members) memberRows.push(`  (${q(id)}, ${q(m)})`)
  })
}
if (groupRows.length) {
  lines.push('insert into groups (id, owner_id, name) values', groupRows.join(',\n') + ';', '')
  lines.push('insert into group_members (group_id, user_id) values', memberRows.join(',\n') + ';', '')
}

for (const key of personas) {
  const P = DATA[key]
  const inviteArticle = (P.feed as Article[]).find((a) => a.id === P.inviteArticle)
  if (P.inviter && inviteArticle) {
    lines.push(
      `insert into invites (code, inviter_id, article_id) values (${q(inviteArticle.authorId)}, ${q(inviteArticle.authorId)}, ${q(inviteArticle.id)});`,
      '',
    )
  }
}

const out = join(dirname(fileURLToPath(import.meta.url)), '../../supabase/seed.sql')
writeFileSync(out, lines.join('\n') + '\n')
console.log('wrote', out)
